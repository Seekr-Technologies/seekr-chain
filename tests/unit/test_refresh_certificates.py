"""Certificate refresh uses the image bootstrap, never application certifi."""

import hashlib
import runpy
import subprocess
from pathlib import Path
from unittest.mock import patch

import certifi
import pytest

ROOT = Path(__file__).resolve().parents[2]
REFRESH = runpy.run_path(str(ROOT / "scripts/refresh_certificates.py"))["refresh_certificates"]
FIXTURES = Path(__file__).parent / "fixtures"


@pytest.fixture
def image_root(tmp_path):
    for name in (
        "docker/build_gates/gate_certificates.py",
        "docker/build_gates/gate_system_bundle.sh",
        "dev/docker/requirements.in",
    ):
        destination = tmp_path / name
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes((ROOT / name).read_bytes())
    # Synthetic, fixed bootstrap independent of future real image pin updates.
    (tmp_path / "docker/certificate-requirements.txt").write_text(
        "certifi==2026.10.23 \\\n    --hash=sha256:"
        + "0" * 64
        + "\npip==26.2.2 \\\n    --hash=sha256:"
        + "1" * 64
        + "\n"
    )
    return tmp_path


def fake_uv(root, bundle):
    def run(command, *, cwd, check, **kwargs):
        assert cwd == root
        assert check is True
        if command[1:3] == ["pip", "install"]:
            assert "--require-hashes" in command
            assert "--only-binary=:all:" in command
            assert command[-1] == str(root / "docker/certificate-requirements.txt")
            target = Path(command[command.index("--target") + 1]) / "certifi/cacert.pem"
            target.parent.mkdir(parents=True)
            target.write_bytes(bundle)
        else:
            assert command[1:3] == ["pip", "compile"]
            assert "--generate-hashes" in command
            constraint = Path(command[command.index("--constraint") + 1])
            assert constraint.read_text() == "certifi==2026.10.23\n"
            output = root / command[command.index("-o") + 1]
            output.write_text("certifi==2026.10.23 \\\n    --hash=sha256:fixture\n")

    return run


def test_refresh_hashes_verified_image_bundle_and_aligns_pins(image_root):
    bundle = (FIXTURES / "emsign-root-g1.pem").read_bytes()
    dev_input = image_root / "dev/docker/requirements.in"
    dev_input.write_text("certifi==2020.1.1\noci-cli\n")
    with (
        patch.object(subprocess, "run", side_effect=fake_uv(image_root, bundle)) as command,
        patch.object(certifi, "where", side_effect=AssertionError("Do not use application certifi")),
    ):
        REFRESH(image_root)
    assert command.call_count == 3
    assert hashlib.sha256(bundle).hexdigest() in (image_root / "docker/build_gates/gate_system_bundle.sh").read_text()
    assert dev_input.read_text() == "certifi==2026.10.23\noci-cli\n"
    for output in ("docker/controller-requirements.txt", "dev/docker/requirements.txt"):
        contents = (image_root / output).read_text()
        assert contents.startswith("# Generated by uv pip compile")
        assert "seekr-certificates-" not in contents


def test_refresh_rejects_compromised_bundle_before_changing_files(image_root):
    bundle = (FIXTURES / "emsign-ecc-root-g3.pem").read_bytes()
    shell = image_root / "docker/build_gates/gate_system_bundle.sh"
    original = shell.read_bytes()
    with (
        patch.object(subprocess, "run", side_effect=fake_uv(image_root, bundle)) as command,
        pytest.raises(SystemExit, match="compromised emSign root"),
    ):
        REFRESH(image_root)
    assert command.call_count == 1
    assert shell.read_bytes() == original
    assert not (image_root / "docker/controller-requirements.txt").exists()


def test_refresh_propagates_failed_hash_install_without_changes(image_root):
    shell = image_root / "docker/build_gates/gate_system_bundle.sh"
    original = shell.read_bytes()
    with (
        patch.object(subprocess, "run", side_effect=subprocess.CalledProcessError(1, ["uv"])),
        pytest.raises(subprocess.CalledProcessError),
    ):
        REFRESH(image_root)
    assert shell.read_bytes() == original


@pytest.mark.parametrize("old_pin", ["certifi==2025.4.26", "pip==26.2.1"])
def test_refresh_rejects_insecure_bootstrap_versions(image_root, old_pin):
    requirements = image_root / "docker/certificate-requirements.txt"
    package = old_pin.split("==")[0]
    lines = ["certifi==2026.10.23", "pip==26.2.2"]
    requirements.write_text("\n".join(old_pin if line.startswith(package + "==") else line for line in lines))
    with patch.object(subprocess, "run") as command, pytest.raises(SystemExit, match=package):
        REFRESH(image_root)
    command.assert_not_called()
