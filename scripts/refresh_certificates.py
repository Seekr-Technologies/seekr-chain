"""Refresh the image CA hash from hash-verified bootstrap requirements.

Does not use the application environment's certifi and never downloads unpinned
artifacts. Review bootstrap version/hash changes before running this command.
"""

import hashlib
import re
import runpy
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def refresh_certificates(root: Path = ROOT) -> None:
    """Validate bootstrap roots, align image pins, and update the shell gate."""
    requirements = root / "docker/certificate-requirements.txt"
    gate = runpy.run_path(str(root / "docker/build_gates/gate_certificates.py"))
    pins = {}
    for package in ("certifi", "pip"):
        match = re.search(rf"(?m)^{package}==([^\s]+)", requirements.read_text())
        if match is None:
            raise SystemExit(f"Missing exact {package} bootstrap pin in {requirements}")
        pins[package] = match[1]
        gate["check_version"](package, match[1])

    with tempfile.TemporaryDirectory(prefix="seekr-certificates-") as temporary:
        target = Path(temporary) / "packages"
        subprocess.run(
            [
                "uv",
                "pip",
                "install",
                "--target",
                str(target),
                "--no-deps",
                "--only-binary=:all:",
                "--require-hashes",
                "-r",
                str(requirements),
            ],
            cwd=root,
            check=True,
        )
        bundle = target / "certifi/cacert.pem"
        gate["check_bundle"](bundle)
        digest = hashlib.sha256(bundle.read_bytes()).hexdigest()
        shell_gate = root / "docker/build_gates/gate_system_bundle.sh"
        updated, count = re.subn(
            r'(?m)^EXPECTED_SHA256="[0-9a-f]{64}"$',
            f'EXPECTED_SHA256="{digest}"',
            shell_gate.read_text(),
        )
        if count != 1:
            raise SystemExit("Expected exactly one EXPECTED_SHA256 in the shell gate")

        # Keep the application lock independent. Only managed image pins follow
        # this bootstrap bundle; no unrelated dependency upgrades are requested.
        dev_input = root / "dev/docker/requirements.in"
        aligned, count = re.subn(r"(?m)^certifi==[^\s]+$", f"certifi=={pins['certifi']}", dev_input.read_text())
        if count != 1:
            raise SystemExit("Expected exactly one certifi pin in dev/docker/requirements.in")
        dev_input.write_text(aligned)
        constraint = Path(temporary) / "constraints.txt"
        constraint.write_text(f"certifi=={pins['certifi']}\n")
        for name in ("docker/controller-requirements", "dev/docker/requirements"):
            subprocess.run(
                [
                    "uv",
                    "pip",
                    "compile",
                    f"{name}.in",
                    "--generate-hashes",
                    "--python-version",
                    "3.12",
                    "--constraint",
                    str(constraint),
                    "-o",
                    f"{name}.txt",
                    "--no-header",
                    "--no-annotate",
                ],
                cwd=root,
                check=True,
                stdout=subprocess.DEVNULL,
            )
            # Do not persist a temporary constraint path in generated headers.
            output = root / f"{name}.txt"
            header = (
                "# Generated by uv pip compile; certifi aligned by uv run inv refresh-certificates.\n"
                f"# uv pip compile {name}.in --generate-hashes --python-version 3.12 -o {name}.txt\n"
            )
            output.write_text(header + output.read_text())
        shell_gate.write_text(updated)
    print(f"Approved image bundle: certifi {pins['certifi']}, SHA256 {digest}")
    print("Review the bundle/pin diff and run unit tests plus uncached image builds.")


if __name__ == "__main__":
    refresh_certificates()
